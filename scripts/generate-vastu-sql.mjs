/**
 * Regenerates supabase/migrations/20260914_vastu_placement.sql from
 *   PraShree-Products-Metadata/vastu-profiles.json  (the nine direction profiles)
 *   PraShree-Products-Metadata/items.json           (secondary_direction / placement_note / placement_detail)
 * Run after editing either file:
 *   npm run vastu:sql
 * Then run the SQL file in the Supabase SQL editor. Idempotent and re-runnable:
 *   - profiles upsert by direction, but a row Monica has saved from /admin
 *     (edited_at set) is left alone so a re-run never clobbers her copy;
 *   - the artwork backfill only writes the three placement columns, by slug.
 */
import { readFileSync, writeFileSync } from 'node:fs'

export const DIRECTIONS = [
  'North', 'North-East', 'East', 'South-East',
  'South', 'South-West', 'West', 'North-West', 'Centre',
]

const profiles = JSON.parse(readFileSync('PraShree-Products-Metadata/vastu-profiles.json', 'utf8'))
const items = JSON.parse(readFileSync('PraShree-Products-Metadata/items.json', 'utf8'))

const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)
const dirList = DIRECTIONS.map(q).join(', ')

const header = `-- ============================================================================
-- PraShree Arts — Vastu placement compass (generated by scripts/generate-vastu-sql.mjs)
-- Run AFTER 20260820_artworks.sql. Idempotent and re-runnable.
-- All copy below is DRAFT pending Monica's confirmation; edit it at /admin.
-- ============================================================================

-- ── Placement fields on artworks ──
ALTER TABLE products ADD COLUMN IF NOT EXISTS secondary_direction TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS placement_note      VARCHAR(140);
ALTER TABLE products ADD COLUMN IF NOT EXISTS placement_detail    TEXT;

-- direction is a pre-existing column: NOT VALID skips checking current rows
-- (they all come from the admin select or items.json) but guards every write
-- from now on. secondary_direction is new, so it validates fully.
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_direction_check;
ALTER TABLE products ADD CONSTRAINT products_direction_check
  CHECK (direction IS NULL OR direction IN (${dirList})) NOT VALID;
ALTER TABLE products DROP CONSTRAINT IF EXISTS products_secondary_direction_check;
ALTER TABLE products ADD CONSTRAINT products_secondary_direction_check
  CHECK (secondary_direction IS NULL OR secondary_direction IN (${dirList}));

CREATE INDEX IF NOT EXISTS idx_products_direction           ON products(direction);
CREATE INDEX IF NOT EXISTS idx_products_secondary_direction ON products(secondary_direction);

-- ── Direction profiles: the wheel's own copy, one row per direction ──
CREATE TABLE IF NOT EXISTS vastu_direction_profiles (
  id             UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
  direction      TEXT NOT NULL UNIQUE
                   CHECK (direction IN (${dirList})),
  label          TEXT NOT NULL,                 -- 'North', 'North-East'
  sanskrit_name  TEXT,                          -- Uttara, Ishanya …
  guardian       TEXT,                          -- traditional presiding figure
  element        TEXT,
  essence        TEXT NOT NULL,                 -- three to five words for the wheel rim
  description    TEXT NOT NULL,                 -- two or three sentences for the reading panel
  sort_order     INTEGER NOT NULL DEFAULT 0,    -- clockwise from North; Centre last
  shows_artworks BOOLEAN NOT NULL DEFAULT TRUE, -- FALSE for Brahmasthana (kept uncrowded)
  edited_at      TIMESTAMPTZ,                   -- set by /admin; seed skips edited rows
  created_at     TIMESTAMPTZ DEFAULT now(),
  updated_at     TIMESTAMPTZ DEFAULT now()
);

DROP TRIGGER IF EXISTS trg_vastu_direction_profiles_updated_at ON vastu_direction_profiles;
CREATE TRIGGER trg_vastu_direction_profiles_updated_at
  BEFORE UPDATE ON vastu_direction_profiles
  FOR EACH ROW EXECUTE FUNCTION update_updated_at();

ALTER TABLE vastu_direction_profiles ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "Public read vastu profiles" ON vastu_direction_profiles;
CREATE POLICY "Public read vastu profiles" ON vastu_direction_profiles
  FOR SELECT USING (true);
DROP POLICY IF EXISTS "Authenticated insert on vastu profiles" ON vastu_direction_profiles;
CREATE POLICY "Authenticated insert on vastu profiles" ON vastu_direction_profiles
  FOR INSERT TO authenticated WITH CHECK (true);
DROP POLICY IF EXISTS "Authenticated update on vastu profiles" ON vastu_direction_profiles;
CREATE POLICY "Authenticated update on vastu profiles" ON vastu_direction_profiles
  FOR UPDATE TO authenticated USING (true) WITH CHECK (true);
DROP POLICY IF EXISTS "Authenticated delete on vastu profiles" ON vastu_direction_profiles;
CREATE POLICY "Authenticated delete on vastu profiles" ON vastu_direction_profiles
  FOR DELETE TO authenticated USING (true);

-- ── Seed the nine profiles (draft copy; rows edited in /admin are untouched) ──
`

const profileRows = profiles.map((p) => `INSERT INTO vastu_direction_profiles
  (direction, label, sanskrit_name, guardian, element, essence, description, sort_order, shows_artworks)
VALUES
  (${q(p.direction)}, ${q(p.label)}, ${q(p.sanskrit_name)}, ${q(p.guardian)}, ${q(p.element)},
   ${q(p.essence)},
   ${q(p.description)},
   ${p.sort_order}, ${p.shows_artworks ? 'TRUE' : 'FALSE'})
ON CONFLICT (direction) DO UPDATE SET
  label = EXCLUDED.label, sanskrit_name = EXCLUDED.sanskrit_name,
  guardian = EXCLUDED.guardian, element = EXCLUDED.element,
  essence = EXCLUDED.essence, description = EXCLUDED.description,
  sort_order = EXCLUDED.sort_order, shows_artworks = EXCLUDED.shows_artworks
WHERE vastu_direction_profiles.edited_at IS NULL;`).join('\n\n')

const mapped = items.filter((i) => i.secondary_direction || i.placement_note || i.placement_detail)
const backfillHeader = `

-- ── Backfill the draft artwork mappings (Appendix B minus the money line) ──
-- Only the three placement columns are written; the primary direction, and
-- every other catalogue field, is owned by 20260820_artworks.sql.
`
const backfillRows = mapped.map((i) => `UPDATE products SET
  secondary_direction = ${q(i.secondary_direction ?? null)},
  placement_note      = ${q(i.placement_note ?? null)},
  placement_detail    = ${q(i.placement_detail ?? null)}
WHERE slug = ${q(i.id)};`).join('\n\n')

const out = header + profileRows + backfillHeader + backfillRows + '\n'
writeFileSync('supabase/migrations/20260914_vastu_placement.sql', out)
console.log(`wrote supabase/migrations/20260914_vastu_placement.sql (${profiles.length} profiles, ${mapped.length} artworks backfilled)`)
