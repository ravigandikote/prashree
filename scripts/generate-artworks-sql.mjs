/**
 * Regenerates supabase/migrations/20260820_artworks.sql from
 * PraShree-Products-Metadata/items.json. Run after editing items.json:
 *   node scripts/generate-artworks-sql.mjs
 * Then run the SQL file in the Supabase SQL editor (idempotent upserts).
 */
import { readFileSync, writeFileSync } from 'node:fs'

const items = JSON.parse(readFileSync('PraShree-Products-Metadata/items.json', 'utf8'))
const q = (v) => (v === null || v === undefined ? 'NULL' : `'${String(v).replace(/'/g, "''")}'`)

const header = `-- ============================================================================
-- PraShree Arts — artworks catalogue (generated by scripts/generate-artworks-sql.mjs)
-- Run AFTER schema.sql + 20260819_refactor.sql. Idempotent: upserts by slug.
-- ============================================================================

-- Catalogue columns for the artworks data
ALTER TABLE products ADD COLUMN IF NOT EXISTS size        TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS size_code   TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS price_range TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS usd         TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS prints      TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS hours       TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS series      TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS form        TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS intent      TEXT;
ALTER TABLE products ADD COLUMN IF NOT EXISTS direction   TEXT;

CREATE INDEX IF NOT EXISTS idx_products_form      ON products(form);
CREATE INDEX IF NOT EXISTS idx_products_series    ON products(series);
CREATE INDEX IF NOT EXISTS idx_products_size_code ON products(size_code);
CREATE INDEX IF NOT EXISTS idx_products_price     ON products(price);

-- Remove the Phase-3 placeholder seeds (superseded by the real catalogue)
DELETE FROM products WHERE slug LIKE 'sample-%';

-- Upsert the catalogue
`

const rows = items.map((i) => `INSERT INTO products
  (name, slug, description, price, images, pdf_url, vastu_note,
   size, size_code, price_range, usd, prints, hours, series, form, intent, direction,
   is_featured, is_available)
VALUES
  (${q(i.name)}, ${q(i.id)}, ${q(i.intent)}, ${i.price},
   ARRAY['/images/products/thumbs/${i.id}.jpg'],
   ${q('/catalogues/' + i.pdf)},
   ${q('Primary Vastu direction: ' + i.direction)},
   ${q(i.size)}, ${q(i.size_code)}, ${q(i.price_range)}, ${q(i.usd)}, ${q(i.prints)},
   ${q(i.hours)}, ${q(i.series)}, ${q(i.form)}, ${q(i.intent)}, ${q(i.direction)},
   FALSE, TRUE)
ON CONFLICT (slug) DO UPDATE SET
  name = EXCLUDED.name, description = EXCLUDED.description, price = EXCLUDED.price,
  images = EXCLUDED.images, pdf_url = EXCLUDED.pdf_url, vastu_note = EXCLUDED.vastu_note,
  size = EXCLUDED.size, size_code = EXCLUDED.size_code, price_range = EXCLUDED.price_range,
  usd = EXCLUDED.usd, prints = EXCLUDED.prints, hours = EXCLUDED.hours,
  series = EXCLUDED.series, form = EXCLUDED.form, intent = EXCLUDED.intent,
  direction = EXCLUDED.direction, is_available = TRUE;`).join('\n\n')

writeFileSync('supabase/migrations/20260820_artworks.sql', header + rows + '\n')
console.log(`wrote supabase/migrations/20260820_artworks.sql (${items.length} artworks)`)
